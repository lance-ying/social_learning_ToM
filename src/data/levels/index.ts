export function loadLevel(levelId: string): GameState {
  let levelConfig = levels[levelId];

  // If level not found, try stripping common suffixes (_1, _ascii, _2, etc.)
  if (!levelConfig) {
    const baseId = levelId.replace(/_(1|2|ascii)$/, "");
    levelConfig = levels[baseId];

    // If still not found, try with _exp4 suffix first, then _true suffix
    if (!levelConfig && baseId.startsWith("sm")) {
      levelConfig = levels[`${baseId}_exp4`] || levels[`${baseId}_true`];
    }
  }

  if (!levelConfig) {
    const availableLevels = Object.keys(levels).join(", ");
    throw new Error(
      `Level "${levelId}" not found. Available levels: ${availableLevels}`,
    );
  }

  const parsedMap = parseAsciiMap(levelConfig.asciiMap);

  const agents = parsedMap.agents?.map((agent, index) => ({
    ...agent,
    ...levelConfig.agentPaths[agent.id],
  }));

  return {
    ...parsedMap,
    agents: agents || [],
    inventory: [],
    p1Inventory: [],
    p2Inventory: [],
    openedBarriers: [],
    stepsRemaining: levelConfig.stepsRemaining,
    goal: levelConfig.goal,
  } as GameState;
}
